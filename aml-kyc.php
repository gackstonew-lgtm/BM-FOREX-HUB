<p>The purpose of this Policy is to:</p>
<ul>
<li>Protect BM FOREX HUB LTD from financial crime.</li>
<li>Verify the identity of customers where appropriate.</li>
<li>Prevent fraud and identity theft.</li>
<li>Comply with applicable laws and regulations.</li>
